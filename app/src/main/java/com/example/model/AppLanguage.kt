            AppLanguage.TAMIL -> tamilStrings
            AppLanguage.MALAYALAM -> malayalamStrings
            AppLanguage.KANNADA -> kannadaStrings
            AppLanguage.ENGLISH -> englishStrings
        }
        return map[key] ?: englishStrings[key] ?: key
    }

