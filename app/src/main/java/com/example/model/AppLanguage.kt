    TAMIL("ta", "Tamil", "தமிழ்", "TA", "குரல் நியூரல் (TA-IN)"),
    MALAYALAM("ml", "Malayalam", "മലയാളം", "ML", "ശബ്ദം ന്യൂറൽ (ML-IN)"),
    KANNADA("kn", "Kannada", "ಕನ್ನಡ", "KN", "ಧ್ವನಿ ನ್ಯೂರಲ್ (KN-IN)");

    companion object {
        fun fromCode(code: String): AppLanguage =
            entries.find { it.code.equals(code, ignoreCase = true) } ?: ENGLISH
    }
}

